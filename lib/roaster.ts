export const FAVORITES = ["저 옷들은 각자 입었을 때는 죄가 없었어요.", "패션에 정답은 없다지만 오답은 있네요.", "일단 신발 벗으세요."];

export type Style = (typeof ROAST_STYLES)[number];
type Pattern = { category: string; template: string; how: string; seen: number };

const BANK_STYLES = (bank as { styles?: Record<string, string[]> }).styles ?? {};
const BANK_PATTERNS = ((bank as { patterns?: Pattern[] }).patterns ?? []) as Pattern[];

export const pick = <T,>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)];
const sampleN = <T,>(arr: T[], n: number): T[] => [...arr].sort(() => Math.random() - 0.5).slice(0, n);
const quoteList = (arr: string[]) => arr.map((s) => `"${s}"`).join(" / ");

/** 기존 예시 + 커뮤니티 은행 문장 */
const examplesOf = (style: Style) => [...style.ex, ...(BANK_STYLES[style.name] ?? [])];

export const pickStyle = (): Style => pick(ROAST_STYLES);
/** 로그에 남기는 스타일 번호 ("s1"~"s25"). 문장 원문 대신 이걸 남긴다. 스타일 순서를 바꾸면 번호도 바뀌니 뒤에만 추가할 것 */
export const styleKey = (style: Style) => "s" + (ROAST_STYLES.indexOf(style) + 1);

